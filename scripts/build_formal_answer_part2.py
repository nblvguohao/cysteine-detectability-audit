"""Part 2: gene-family regularities in the annotated Cys sites."""
from pathlib import Path

from docx_helpers import bullets, figure, heading, para, table

FIG_DIR = Path(__file__).resolve().parents[1] / "deliverables" / "figures"


def build_part2(doc, fam, famrows, pubmap):
    heading(doc, "二、能不能从基因家族找规律，缩小研究范围", 1)
    para(doc, "这是老师和师姐提的问题，也是今天新做的分析，在全番茄蛋白组上首次系统测了这件事。"
              "结论**不对称**：家族层面的富集是真的、有统计支持，能帮您从“做什么功能方向”缩小到“查哪个基因家族、"
              "查哪个蛋白”；但再往下一级，具体到“家族里哪一列 Cys 会被修饰”，序列保守性本身**不是**可靠向导——"
              "课题组自己发表的两个位点就是反例，详见 2.2。", size=10)

    heading(doc, "2.1 蛋白（家族）层面的富集：真实，但部分与检测便利性纠缠", 2)
    bullets(doc, [
        f"在全番茄蛋白组内做了 {fam['n_pairs_analyzed']} 次同源蛋白两两比对（序列一致性 30–95%），"
        f"得到 {fam['n_cys_rows']} 组“两个同源蛋白在同一列都是 Cys”的配对，统计"
        f"“一个位点已被记录时，同源蛋白对应列的 Cys 是否也被记录”：",
        f"总体上，源位点已被记录时，同源位点被记录的概率是 **{fam['p1']}**；源位点未被记录时只有 **{fam['p0']}**，"
        f"相差 **{fam['ratio']} 倍**。这个倍数随同源程度提高而提高：{fam['identity_bin_desc']}——"
        f"越近的同源蛋白，家族富集信号越强，这一点对“先定位家族、再定位到近缘旁系同源基因”这个策略是直接支持。",
        f"**关键对照**：把配对限制到“两个同源 Cys 落在不同酶切肽段”（即排除掉“两者共享同一条可测/不可测肽段”这条最"
        f"简单的捷径），倍数几乎不变（{fam['ratio_diff']} 倍，对全体 {fam['ratio']} 倍）。"
        f"这说明这个家族富集**不是单纯由“同源蛋白恰好共享同一条可测肽段”造成的**——如果是，限制到不同肽段后倍数应明显"
        f"下降，但没有。残留的解释可能是：家族成员共享的蛋白丰度/亚细胞定位/在富集流程中的整体可及性，"
        f"也可能有一部分真实的化学环境保守性，本数据集无法把两者继续拆开。",
    ])

    heading(doc, "表 2　同源位点标注一致性（按序列一致性分层，末行为肽段对照）", 3)
    para(doc, "P(同源位点已记录 | 源位点已记录) 与 P(同源位点已记录 | 源位点未记录) 的比值越大，"
              f"说明“一个位点被记录”对预测同源列位点越有信息量。全库背景值（任意被检测蛋白的任意 Cys 被记录的比例）为 "
              f"**{fam['base_rate']}**，可与两栏对照。", size=9)
    header = ["序列一致性 / 分层", "同源对定义", "配对数", "P(同源已记录\n|源已记录)", "P(同源已记录\n|源未记录)", "倍数"]
    table(doc, header, fam["concordance_rows"], widths_cm=[2.0, 3.6, 1.6, 2.6, 2.6, 1.2], size=8.3,
          highlight_rows=(4,))

    figure(doc, FIG_DIR / "family_concordance.png",
           "图 1　同源位点标注一致性。A：三个序列一致性区间下，源位点已记录（深蓝）与未记录（浅蓝）时，"
           "同源蛋白对应列 Cys 被记录的概率；灰色虚线为全库背景值 27.4%。一致性越高，两者差距越大。"
           "B：把配对限制到“两个同源 Cys 不落在同一条酶切肽段”（右）后，概率与倍数几乎不变（均为 1.71×），"
           "说明这个富集不是靠“同源蛋白恰好共享同一条可测/不可测肽段”这条捷径得到的。数据即表 2，"
           "见 results/family_pair_concordance.csv。", width_cm=15.5)

    bullets(doc, [
        f"**一个容易高估的点，需要澄清**：已标注 Cys 在同源蛋白里“本身是不是 Cys”的保守率是 **{fam['cons_lab']}**，"
        f"未标注 Cys 是 **{fam['cons_unl']}**——两者**几乎没有差别**。也就是说，"
        f"“这个 Cys 有没有被记录过”和“这个位置在进化上是否倾向于保留为 Cys”是两件基本独立的事，"
        f"后者不能作为筛选依据。真正有信息量的是表 2 的“同源位点是否也被记录”，不是“这一列是否保守为 Cys”。",
    ])

    heading(doc, "2.2 位点（残基列）层面：具体选哪一个 Cys，不能只看保守性——两个反例", 2)
    para(doc, "把课题组自己发表、经过湿实验确认的两个巯基化位点，映射到本项目候选蛋白所在的同一个家族，"
              "看它们本身在近缘同源蛋白里保不保守：", size=10)
    header2 = ["已发表位点", "映射到的本项目候选蛋白", "同源比对结果", "结论"]
    table(doc, header2, pubmap, widths_cm=[3.4, 3.6, 4.8, 2.2], size=8.3, highlight_rows=tuple(range(len(pubmap))))
    bullets(doc, [
        "**两个已发表位点都不落在家族保守列上**：C396 在 WRKY 家族的这个候选蛋白里对应的是缬氨酸，C35 在 ERF 家族的"
        "候选蛋白里对应的是谷氨酸，都不是 Cys；另外两次映射尝试因区域本身比对不上而无法比较。",
        "这与直觉相反，但从机制上讲得通：**真正被功能验证的可逆氧化还原位点，往往是家族分化后某个成员新获得的、"
        "位于表面或无序区的 Cys**，而不是整个家族从祖先延续下来的保守 Cys——保守 Cys 更常见的角色是结构性的"
        "（配位金属、形成二硫键），修饰后果是破坏结构而非可逆开关。第一部分已指出 XP_004233015.1 的两个 Cys 正是"
        "这种结构性的锌指配位残基，2.3 节会给出这一点的家族层面交叉验证。",
        "**因此策略应该是**：“功能方向 → 基因家族 → 缩小到某些基因”这条路径在**家族**这一级成立"
        "（2.1 节的富集是真实信号，可用来决定优先查哪个基因家族/哪个近缘旁系同源基因）；但**家族内部挑选具体残基**"
        "不能再退回到“找最保守的 Cys”，而要用 2.3 节这种“家族里这一列 Cys 有没有被记录过”的交叉检验，"
        "结合模型排名和可测性一起判断。",
    ])

    heading(doc, "2.3 落到您这 15 个蛋白：每个首选位点在家族里有没有过往记录", 2)
    para(doc, "对锁定表里每个蛋白的模型首选与次选 Cys，统计“家族内已被检测到的同源蛋白中，有多少在对应列也记录过"
              "巯基化”（记录数/检出同源数）。这是独立于第一部分“证据位点”的另一条交叉检验：证据位点看的是"
              "这个蛋白自己或强同源体是否被直接观察到过，这里看的是**整个家族**在这一列上的历史记录密度。", size=9.5)
    table(doc, ["蛋白", "模型首选（家族记录）", "模型次选（家族记录）", "备注"], famrows,
          widths_cm=[3.2, 3.4, 3.4, 5.4], size=8.3, highlight_rows=(4, 9, 10, 13))
    bullets(doc, [
        "**三个值得特别注意的情况**：XP_004233015.1 的两个锌指 Cys，家族里约 75 个同源蛋白在同一列也是 Cys，"
        "其中被质谱检测到的 11 个里一次都没有被记录过（0/5、0/6）——与 2.2 节的结构解释完全吻合，进一步支持这两个位点更可能是结构性的，不是氧化还原开关；"
        "Solyc12g006920.2.1（PP2A-B56）和 WXY-3 都出现“模型首选家族零记录、次选或证据位点反而有家族记录”的情况，"
        "**建议按第一部分给出的证据位点/次选优先，而不是机械按模型第一名**。",
        "逐位点明细见 `results/family_candidate_site_conservation.csv`（含具体同源蛋白编号与一致性），"
        "方法与全部阈值见 `results/family_site_conservation_audit.json`。",
    ])
